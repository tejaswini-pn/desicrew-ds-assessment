"""Run a scripted 12-turn conversation and save the transcript to demo_transcript.md.

The script deliberately exercises: follow-ups with pronouns, a repeated question,
several topic switches, a switch back to an earlier topic, an out-of-scope question and chit-chat.
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(__file__))
from assistant import SupportAssistant  # noqa: E402

TURNS = [
    ("Hi, I want to set up auto-debit for my premium. How do I do it?", "new topic"),
    ("How long does that take to start working?", "follow-up with pronoun"),
    ("My mandate got rejected last time. Why might that happen?", "follow-up"),
    ("Can I pay monthly if I use it?", "follow-up - should reuse NACH context"),
    ("Different question - I took a home loan and the bank wants my policy. What do I need to do?", "topic switch -> assignment"),
    ("What happens to my nominee if I do that?", "follow-up; nominee linked to assignment"),
    ("And once the loan is repaid?", "follow-up"),
    ("Sorry, how do I set up the auto-debit again?", "repeat question -> recap, no full repeat"),
    ("If I miss a premium, am I still covered?", "switch back to payments, new sub-topic"),
    ("OK, what documents does my family need to file a death claim?", "topic switch -> claims"),
    ("How quickly will they get paid?", "follow-up"),
    ("Do you also offer car insurance?", "out of scope -> must not invent"),
    ("Thanks, that's all!", "chit-chat close"),
]


def main():
    bot = SupportAssistant()
    lines = ["# Demo conversation — Suraksha Help support assistant\n",
             f"Model: `{bot.model}` · {len(TURNS)} turns · generated by `demo_conversation.py`\n"]
    for i, (msg, purpose) in enumerate(TURNS, 1):
        t = bot.chat(msg)
        flags = [f"topic: *{t['topic']}*"]
        if t["topic_switch"]:
            flags.append("**topic switch detected**")
        if t["repeat"]:
            flags.append("**repeat detected**")
        lines += [f"\n## Turn {i} — {purpose}\n",
                  f"**User:** {msg}\n",
                  f"> _{' · '.join(flags)} · standalone query: \"{t['standalone_query']}\"_\n",
                  f"**Assistant:** {t['assistant']}\n",
                  f"_Cited:_ {', '.join(t['cites']) or '—'}\n"]
        print(f"[{i}/{len(TURNS)}] {msg}\n -> {t['assistant'][:160]}...\n")
        time.sleep(1)
    lines += ["\n## Session ledger at end (what the assistant knows it has already told the user)\n"]
    lines += [f"- `{c}` — {n}" for c, n in bot.memory.ledger.items()]
    out = os.path.join(os.path.dirname(__file__), "demo_transcript.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("Saved", out)


if __name__ == "__main__":
    main()
